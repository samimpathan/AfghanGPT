export const STRINGS: Record<Lang, Dict> = { ps, en, fa, ar };

export function t(lang: Lang, key: string): string {
  return STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
}

export function dirOf(lang: Lang): "rtl" | "ltr" {
  return LANGS.find((l) => l.code === lang)?.dir ?? "rtl";
}

/** React hook for the studio pages: current language + t() + setter.
 * Reads/writes the same "samim-ai-lang" key the chat UI uses, so the
 * language stays in sync across chat and studios. */
export function useLang() {
  const [lang, setLangState] = useState<Lang>("ps");
  useEffect(() => {
    try {
      const v = localStorage.getItem("samim-ai-lang");
      if (v === "ps" || v === "en" || v === "fa" || v === "ar") setLangState(v as Lang);
    } catch {
      // ignore
    }
  }, []);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("samim-ai-lang", l);
      document.documentElement.lang = l;
      document.documentElement.dir = dirOf(l);
    } catch {
      // ignore
    }
  }, []);
  const tFn = useCallback((key: string): string => t(lang, key), [lang]);
  return { lang, setLang, t: tFn };
}
